CREATE TABLE reschedule_proposals (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version bigint NOT NULL,
 plan_id bigint NOT NULL REFERENCES plans(id) ON DELETE CASCADE,
 created_by_id bigint NOT NULL REFERENCES users(id),
 base_agreement_version integer NOT NULL,
 proposed_date date NOT NULL,
 proposed_time time(0),
 place_option_id bigint,
 place_label varchar(120) NOT NULL,
 latitude double precision NOT NULL,
 longitude double precision NOT NULL,
 address varchar(255),
 reason varchar(500),
 status varchar(24) NOT NULL CHECK (status IN ('VOTING','APPROVED','REJECTED','APPLIED','WITHDRAWN','EXPIRED','SUPERSEDED')),
 created_at timestamp(6) with time zone NOT NULL,
 expires_at timestamp(6) with time zone NOT NULL
);
CREATE INDEX idx_reschedule_plan ON reschedule_proposals(plan_id, id);
CREATE TABLE reschedule_votes (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 proposal_id bigint NOT NULL REFERENCES reschedule_proposals(id) ON DELETE CASCADE,
 user_id bigint NOT NULL REFERENCES users(id),
 accepted boolean NOT NULL,
 updated_at timestamp(6) with time zone NOT NULL,
 CONSTRAINT uq_reschedule_vote UNIQUE(proposal_id,user_id)
);
